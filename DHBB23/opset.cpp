const int N = 1e7 + 10;
const int MOD = 1e9 + 7;
int n, k, d;
bool removed[N];
int best[N], limit[N], cnt[N], sum[N];
main() {
    cin.tie(nullptr)->sync_with_stdio(false);
    //freopen(Task".inp", "r", stdin);
    cin >> n >> k >> d;
    for (int i = 0, x; i < k; i++)
        cin >> x, removed[x] = true;
    int maxBest = 0, j = 0;
    for (int i = 1; i <= n; i++) {
        if (removed[i]) {
            best[i] = -1;
            continue;
        }
        while (j < i - d - 1)
            maxBest = max(maxBest, best[++j]);
        best[i] = maxBest + 1;
        limit[best[i]] = max(limit[best[i]], i);
    }
    for (int i = 1; i <= n; i++)
        maxBest = max(maxBest, best[i]);
    for (int i = 1; i <= n; i++) {
        if (removed[i]) cnt[i] = 0;
        else if (best[i] == 1) cnt[i] = 1;
        else {
            int l = limit[best[i] - 2] + 1, r = limit[best[i] - 1];
            r = min(r, i - d - 1);
            cnt[i] = (sum[r] - sum[l - 1] + MOD) % MOD;
        }
        sum[i] = (sum[i - 1] + cnt[i]) % MOD;
    }
    int ans = 0;
    for (int i = 1; i <= n; i++) if (best[i] == maxBest)
        ans = (ans + cnt[i]) % MOD;
    cout << maxBest << '\n' << ans;
    return 0;
}
