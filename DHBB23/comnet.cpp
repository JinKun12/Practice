const int N = 1e5 + 10;
const int M = 2e5 + 10;
struct DSU {
    int par[N], sz[N];
    void make_set(int u) {
        par[u] = u;
        sz[u] = 1;
    }
    void init(int n) {
        for (int i = 1; i <= n; i++) make_set(i);
    }
    int Find(int u) {
        return par[u] == u ? u : par[u] = Find(par[u]);
    }
    bool Merge(int u, int v) {
        u = Find(u);
        v = Find(v);
        if (u == v) return false;
        if (sz[u] < sz[v]) swap(u, v);
        par[v] = u;
        sz[u] += sz[v];
        return true;
    }
} T;
int n, m;
struct Edge {
    int u, v, w;
} a[M];
bool inTree[M];
main() {
    cin.tie(nullptr)->sync_with_stdio(false);
    //freopen(Task".inp", "r", stdin);
    cin >> n >> m;
    for (int i = 1; i <= m; i++)
        cin >> a[i].u >> a[i].v >> a[i].w;
    sort(a + 1, a + m + 1, [](Edge p, Edge q) {
        return p.w > q.w;
    });
    T.init(n);
    for (int i = 1; i <= m; i++)
        inTree[i] = T.Merge(a[i].u, a[i].v);
    int numComp = 0;
    for (int i = 1; i <= n; i++) if (T.Find(i) == i)
        numComp++;
    int used = 0, ans = 0;
    for (int i = m; i >= 1; i--) if (!inTree[i] && used < numComp - 1)
        ans += a[i].w, used++;
    cout << ans;
    return 0;
}
